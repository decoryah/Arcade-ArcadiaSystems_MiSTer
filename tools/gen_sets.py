#!/usr/bin/env python3
"""Make tools/arcadia_sets.py (the ROM sets) from MAME's driver.

    python3 tools/gen_sets.py <mame>/src/mame/amiga/arsystems.cpp > tools/arcadia_sets.py

Takes, for every set: name, parent, title, year, the ROM board files (user3: name, CRC, offset, high or low byte), the fill of
the unused board (ROMREGION_ERASEFF or zero; MAME zeroes regions up to 4 MB that ask for nothing), the low-byte permutation of
its driver init (generic_decode), and whether it uses Aaargh's map. The BIOS is MAME's default for every set (OnePlay 3.00).
"""
import re
import sys


def main():
    src = open(sys.argv[1], encoding='utf-8').read()

    # driver inits: init_xxx() { init_arcadia(); generic_decode("user3", b7..b0); }
    perms = {'init_arcadia': [7, 6, 5, 4, 3, 2, 1, 0]}
    for m in re.finditer(r'void arcadia_amiga_state::(init_\w+)\(\)\s*\{\s*init_arcadia\(\);\s*'
                         r'generic_decode\("user3",\s*([\d,\s]+)\);', src):
        perms[m.group(1)] = [int(x) for x in m.group(2).split(',')]

    games = {}
    for m in re.finditer(r'^GAME\(\s*(\d+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*\w+,\s*(\w+),\s*\w+,\s*"([^"]*)",\s*"([^"]*)",\s*([^)]*)\)',
                         src, re.M):
        year, name, parent, machine, inputs, init, maker, title, flags = m.groups()
        games[name] = dict(year=int(year), parent=parent, machine=machine, inputs=inputs, init=init, title=title, flags=flags.strip())

    sets = []
    for m in re.finditer(r'ROM_START\(\s*(\w+)\s*\)(.*?)ROM_END', src, re.S):
        name, body = m.group(1), m.group(2)
        if name == 'ar_bios':
            continue
        g = games[name]
        reg = re.search(r'ROM_REGION16_BE\(\s*0x180000,\s*"user3",\s*(\w+)\s*\)(.*?)(?=ROM_REGION|$)', body, re.S)
        fill = 0xFF if reg.group(1) == 'ROMREGION_ERASEFF' else 0x00
        files = []
        for f in re.finditer(r'ROM_LOAD16_BYTE\(\s*"([^"]+)",\s*(0x[0-9a-fA-F]+),\s*(0x[0-9a-fA-F]+),\s*(BAD_DUMP\s+)?CRC\((\w+)\)', reg.group(2)):
            fname, off, length, bad, crc = f.groups()
            off = int(off, 16)
            files.append((fname, crc.lower(), off & ~1, 'lo' if off & 1 else 'hi', int(length, 16), bool(bad)))
        sets.append(dict(name=name, parent=g['parent'], title=g['title'], year=g['year'], argh=g['machine'] == 'argh',
                         four_way=g['inputs'] == 'arcadia_4way', perm=perms[g['init']], fill=fill,
                         not_working='MACHINE_NOT_WORKING' in g['flags'], files=files))

    print('# Generated by tools/gen_sets.py from MAME 0.289 src/mame/amiga/arsystems.cpp: do not edit.')
    print('# files: (name, crc32, word offset in the ROM board, "hi" even bytes / "lo" odd bytes, length, bad dump)')
    print()
    print('KICKSTART = ("315093-01.u2", "a6ce1636")          # Kickstart 1.3, 256 KB, big-endian words')
    print('BIOS = [("scpa_01-hi_v3.0.u12", "2d8e1a06", 0, "hi"),  # OnePlay 3.00, MAME\'s default BIOS (scrambled)')
    print('        ("scpa_01-lo_v3.0.u16", "e4f38fab", 0, "lo")]')
    print()
    print('SETS = [')
    for s in sets:
        print('    dict(name=%r, parent=%r, title=%r, year=%d, argh=%r, four_way=%r, not_working=%r,' %
              (s['name'], s['parent'], s['title'], s['year'], s['argh'], s['four_way'], s['not_working']))
        print('         perm=%r, fill=0x%02X, files=[' % (s['perm'], s['fill']))
        for f in s['files']:
            print('             (%r, %r, 0x%05X, %r, 0x%X, %r),' % f)
        print('         ]),')
    print(']')


if __name__ == '__main__':
    main()
